function buildProject(input: CloudinaryProjectInput): Project {
  const copy = copyByKind[input.kind];
  const eventEn = input.event ? ` for ${input.event}` : "";

  return {
    projectCode: input.projectCode,
    cloudinaryFolder: input.cloudinaryFolder,
    slug: input.slug,
    year: input.year,
    image: input.image,
    imageAlt: `${input.title.en} — CPS project`,
    imageAltAr: input.imageAltAr ?? `${input.title.ar} — مشروع نفّذته CPS`,
    gallery: input.gallery,
    motionVideo: input.motionVideo,
    industrySlug: input.industrySlug,
    serviceSlug: serviceByKind[input.kind].primary,
    serviceSlugs: [...serviceByKind[input.kind].all],
    boothTypeSlug: input.kind === "booth" ? "custom" : undefined,
    locationSlug: input.locationSlug,
    event: input.event,
    eventAr: input.eventAr,
    size: input.size,
    technologies: [...serviceByKind[input.kind].tech],
    featured: input.featured,
    clientName: input.clientName,
    en: {
      title: input.title.en,
      category: copy.categoryEn,
      summary: `A ${copy.categoryEn.toLowerCase()} produced and delivered by CPS for ${input.clientName.en}${eventEn}.`,
      scopeOfWork: copy.scopeEn,
      challenge: copy.challengeEn,
      approach: copy.approachEn,
      outcome: copy.outcomeEn,
    },
    ar: {
      title: input.title.ar,
      category: copy.categoryAr,
      summary: input.summaryAr,
      scopeOfWork: copy.scopeAr,
      challenge: copy.challengeAr,
      approach: copy.approachAr,
      outcome: copy.outcomeAr,
    },
  };
}

